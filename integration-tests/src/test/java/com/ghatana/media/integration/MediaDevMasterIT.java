    private static byte[] wavBytes(int rate, int channels, short[] samples) {
        ByteBuffer out = ByteBuffer.allocate(44 + samples.length * 2).order(ByteOrder.LITTLE_ENDIAN);
        out.putInt(0x46464952).putInt(36 + samples.length * 2).putInt(0x45564157);
        out.putInt(0x20746d66).putInt(16).putShort((short) 1).putShort((short) channels).putInt(rate).putInt(rate * channels * 2)
                .putShort((short) (channels * 2)).putShort((short) 16);
        out.putInt(0x61746164).putInt(samples.length * 2);
        out.asShortBuffer().put(samples);
        return out.array();
    }

    private static short[] tonePcm(int rate, double hz, int frames) {
        short[] out = new short[frames];
        for (int i = 0; i < frames; i++) out[i] = (short) Math.round(12_000 * Math.sin(2 * Math.PI * hz * i / rate));
        return out;
    }

    private static short[] stereoTone(int frames) {
        short[] out = new short[frames * 2];
        for (int i = 0; i < frames; i++) {
            out[2 * i] = (short) Math.round(12_000 * Math.sin(2 * Math.PI * 220.0 * i / 48_000));
            out[2 * i + 1] = out[2 * i];
        }
        return out;
    }

    private static byte[] sixChannel() {
        short[] samples = new short[4800 * 6];
        for (int i = 0; i < samples.length; i++) samples[i] = (short) (1000 * Math.sin(i * 0.05));
        return wavBytes(48_000, 6, samples);
    }

    /** Durable artifact rows of the principal whose content type or metadata mentions {@code needle}. */
    private static int rows(String tenant, String principal, String needle) throws Exception {
        try (var connection = DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
             var statement = connection.prepareStatement("SELECT count(*) FROM media_artifacts WHERE tenant_id=? AND principal_id=? "
                     + "AND (content_type=? OR metadata_json LIKE ?)")) {
            statement.setString(1, tenant);
            statement.setString(2, principal);
            statement.setString(3, needle);
            statement.setString(4, "%" + needle + "%");
            try (var row = statement.executeQuery()) {
                row.next();
                return row.getInt(1);
            }
        }
    }
