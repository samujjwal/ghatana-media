-- Rights and consent authority (owner decision, 2026-11-14): "Uploader + reviewer (Recommended): The uploader
-- states rights and consent for each source version. A second person must confirm before any voice or likeness
-- use, or before any external delivery. Every statement records who gave it, when and for which exact file, and
-- can be revoked."
--
-- An attestation binds a statement to one tenant, one artifact id, one exact artifact version and its content
-- digest. A confirmation (a DIFFERENT principal) or a revocation is a separate append-only event row. Nothing in
-- this schema is generated by software on its own behalf: every row carries the authenticated principal who
-- gave it. A new artifact version never inherits an earlier version's rows because the version is part of the key
-- every resolver reads by.
CREATE TABLE media_rights_attestations (
    tenant_id VARCHAR(255) NOT NULL,
    attestation_id VARCHAR(256) NOT NULL,
    artifact_id VARCHAR(255) NOT NULL,
    artifact_version VARCHAR(71) NOT NULL,
    content_sha256 CHAR(64) NOT NULL,
    attesting_principal_id VARCHAR(255) NOT NULL,
    attested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    statement_kind VARCHAR(40) NOT NULL,
    scopes_csv TEXT NOT NULL,
    basis TEXT NOT NULL,
    supporting_document_artifact_ref VARCHAR(512) NOT NULL DEFAULT '',
    requested_confirmer_principal_id VARCHAR(255) NOT NULL DEFAULT '',
    expires_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (tenant_id, attestation_id),
    CONSTRAINT media_rights_attestation_attester_unique UNIQUE (tenant_id, attestation_id, attesting_principal_id),
    CONSTRAINT media_rights_attestation_version_digest_check CHECK (
        CHAR_LENGTH(artifact_version) = 71 AND artifact_version = 'sha256:' || content_sha256),
    CONSTRAINT media_rights_attestation_kind_check CHECK (
        statement_kind IN ('MEDIA_RIGHTS', 'IDENTIFIABLE_PERSON_CONSENT')),
    CONSTRAINT media_rights_attestation_scopes_check CHECK (
        scopes_csv <> '' AND scopes_csv ~ '^(PROCESSING|VOICE_OR_LIKENESS_USE|EXTERNAL_DELIVERY)(,(PROCESSING|VOICE_OR_LIKENESS_USE|EXTERNAL_DELIVERY))*$'),
    CONSTRAINT media_rights_attestation_basis_check CHECK (CHAR_LENGTH(basis) BETWEEN 1 AND 2000),
    CONSTRAINT media_rights_attestation_confirmer_check CHECK (requested_confirmer_principal_id <> attesting_principal_id),
    CONSTRAINT media_rights_attestation_expiry_check CHECK (expires_at IS NULL OR expires_at > attested_at)
);

CREATE INDEX idx_media_rights_attestations_artifact
    ON media_rights_attestations (tenant_id, artifact_id, artifact_version, attested_at);

CREATE TABLE media_rights_attestation_events (
    tenant_id VARCHAR(255) NOT NULL,
    attestation_id VARCHAR(256) NOT NULL,
    event_kind VARCHAR(16) NOT NULL,
    principal_id VARCHAR(255) NOT NULL,
    -- Copy of the attester, bound by foreign key, so the second-person rule is a plain constraint
    -- (the same migration must run on the H2 lineage fixture, so no PostgreSQL-only triggers).
    attesting_principal_id VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    detail TEXT NOT NULL DEFAULT '',
    -- At most one confirmation and one revocation per attestation.
    PRIMARY KEY (tenant_id, attestation_id, event_kind),
    FOREIGN KEY (tenant_id, attestation_id, attesting_principal_id)
        REFERENCES media_rights_attestations (tenant_id, attestation_id, attesting_principal_id),
    CONSTRAINT media_rights_event_self_confirmation_check CHECK (
        event_kind <> 'CONFIRMED' OR principal_id <> attesting_principal_id),
    CONSTRAINT media_rights_event_kind_check CHECK (event_kind IN ('CONFIRMED', 'REVOKED')),
    CONSTRAINT media_rights_event_detail_check CHECK (
        CHAR_LENGTH(detail) <= 2000 AND (event_kind <> 'REVOKED' OR CHAR_LENGTH(detail) >= 1))
);

COMMENT ON TABLE media_rights_attestations IS
    'Append-only (the store has no UPDATE/DELETE path) per-version uploader statements of rights and consent; the principal is the authenticated caller.';
COMMENT ON TABLE media_rights_attestation_events IS
    'Append-only second-person confirmations and revocations of an attestation.';
