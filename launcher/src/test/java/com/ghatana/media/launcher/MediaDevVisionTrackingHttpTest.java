    @Test
    @Order(3)
    void roiDetectionAndSceneTextAreReturnedInSourceFrameCoordinates() throws Exception {
        Path root = Files.createTempDirectory("media-dev-vision-roi-");
        MediaRuntime runtime = runtime(root);
        HttpServer server = server(runtime, RIGHTS.verdict(Verdict.ADMITTED));
        try {
            byte[] video = TrackingVideoFixture.generate(ffmpeg, Files.createTempDirectory(work, "gen-"), false);
            MediaArtifact source = upload(runtime, "roi.mp4", "video/mp4", video);
            // Video frame 0: car at x=20,y=250 inside ROI (0,220)-(300,350); text GHATANA inside ROI (0,0)-(320,100).
            HttpResponse<byte[]> detect = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "roi-det-1",
                    "artifactId", source.artifactId(), "artifactVersionId", source.version().value(),
                    "tasks", List.of("detect"), "frameIndex", 0, "roi", roi(0, 220, 300, 130)));
            assertThat(detect.statusCode()).as(new String(detect.body())).isEqualTo(201);
            Map<String, Object> detectDoc = readDocument(runtime, (String) map(detect).get("outputId"));
            System.out.println("J05-ROI-DETECT " + JSON.writeValueAsString(detectDoc));
            Map<String, Object> results = obj(detectDoc.get("results"));
            List<Map<String, Object>> objects = list(results.get("objects"));
            // Florence-2 may call the sprite a car or a truck depending on the crop context; both are the car sprite.
            java.util.function.Predicate<Map<String, Object>> carLike = o -> "car".equals(o.get("label")) || "truck".equals(o.get("label"));
            assertThat(objects).as("labels " + objects).anyMatch(carLike);
            Map<String, Object> carBox = objects.stream().filter(carLike).findFirst().orElseThrow();
            double[] box = box(obj(carBox.get("boundingBox")));
            double[] truth = TrackingVideoFixture.carBox(0);
            assertThat(TrackingVideoFixture.iou(box, truth)).isGreaterThanOrEqualTo(0.75);
            assertThat(box[0]).isGreaterThanOrEqualTo(0);
            assertThat(box[1]).isGreaterThanOrEqualTo(220);
            assertThat(obj(detectDoc.get("frame"))).containsEntry("frameIndex", 0).containsEntry("pts", 0);

            HttpResponse<byte[]> ocr = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "roi-ocr-1",
                    "artifactId", source.artifactId(), "artifactVersionId", source.version().value(),
                    "tasks", List.of("ocr"), "frameIndex", 0, "roi", roi(0, 0, 320, 100)));
            assertThat(ocr.statusCode()).as(new String(ocr.body())).isEqualTo(201);
            Map<String, Object> ocrDoc = readDocument(runtime, (String) map(ocr).get("outputId"));
            System.out.println("J05-ROI-OCR " + JSON.writeValueAsString(ocrDoc));
            Map<String, Object> sceneText = obj(obj(ocrDoc.get("results")).get("sceneText"));
            assertThat(((String) sceneText.get("fullText")).toUpperCase()).contains("GHATANA");
            for (Map<String, Object> region : list(sceneText.get("regions"))) {
                List<?> quad = (List<?>) region.get("quad");
                for (int i = 0; i < quad.size(); i++) {
                    double v = number(quad.get(i));
                    assertThat(v).isBetween(0.0, i % 2 == 0 ? 640.0 : 360.0);
                }
            }

            // Image source: same ROI semantics on a still.
            MediaArtifact image = upload(runtime, "still.png", "image/png", TrackingVideoFixture.background());
            HttpResponse<byte[]> imageOcr = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "roi-img-1",
                    "artifactId", image.artifactId(), "artifactVersionId", image.version().value(),
                    "tasks", List.of("ocr"), "roi", roi(0, 0, 320, 100)));
            assertThat(imageOcr.statusCode()).as(new String(imageOcr.body())).isEqualTo(201);
            assertThat(((String) obj(obj(readDocument(runtime, (String) map(imageOcr).get("outputId")).get("results"))
                    .get("sceneText")).get("fullText")).toUpperCase()).contains("GHATANA");
        } finally {
            server.stop(0);
        }
    }

    @Test
    @Order(4)
    void malformedNegativeZeroSizeAndOutOfFrameRoiAreRefusedBeforeAnyReadOrModelCall() throws Exception {
        Path root = Files.createTempDirectory("media-dev-vision-roi-bad-");
        MediaRuntime runtime = runtime(root);
        HttpServer server = server(runtime, RIGHTS.verdict(Verdict.ADMITTED));
        try {
            byte[] video = TrackingVideoFixture.generate(ffmpeg, Files.createTempDirectory(work, "gen-"), false);
            MediaArtifact clip = upload(runtime, "bad-roi.mp4", "video/mp4", video);
            MediaArtifact image = upload(runtime, "bad-roi.png", "image/png", TrackingVideoFixture.background());
            int calls = proxy.analyzeCalls.get();
            int rightsCalls = RIGHTS.calls.get();

            // Structural faults: refused even for an artifact that does not exist, so no lookup or read happened.
            String ghost = "no-such-artifact";
            String ghostVersion = "sha256:" + "0".repeat(64);
            Map<String, Object> structural = new LinkedHashMap<>();
            structural.put("negative x", roi(-1, 0, 10, 10));
            structural.put("negative y", roi(0, -5, 10, 10));
            structural.put("zero width", roi(0, 0, 0, 10));
            structural.put("zero height", roi(0, 0, 10, 0));
            structural.put("negative size", roi(0, 0, -3, 10));
            Map<String, String> codes = Map.of("negative x", "ROI_NEGATIVE", "negative y", "ROI_NEGATIVE",
                    "zero width", "ROI_ZERO_SIZE", "zero height", "ROI_ZERO_SIZE", "negative size", "ROI_ZERO_SIZE");
            for (var entry : structural.entrySet()) {
                HttpResponse<byte[]> refused = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId",
                        "bad-" + entry.getKey().replace(' ', '-'), "artifactId", ghost, "artifactVersionId",
                        ghostVersion, "tasks", List.of("detect"), "roi", entry.getValue()));
                assertThat(refused.statusCode()).as(entry.getKey() + " " + new String(refused.body())).isEqualTo(422);
                assertThat(new String(refused.body())).contains(codes.get(entry.getKey()));
            }
            Map<String, Object> fractional = roi(0, 0, 10, 10);
            fractional.put("width", 10.5);
            Map<String, Object> missing = roi(0, 0, 10, 10);
            missing.remove("height");
            Map<String, Object> stringy = roi(0, 0, 10, 10);
            stringy.put("x", "0");
            Map<String, Object> extra = roi(0, 0, 10, 10);
            extra.put("z", 1);
            Map<String, Object> overflow = roi(Integer.MAX_VALUE, 0, 1, 1);
            for (Map<String, Object> bad : List.of(fractional, missing, stringy, extra, overflow)) {
                HttpResponse<byte[]> refused = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "bad-shape",
                        "artifactId", ghost, "artifactVersionId", ghostVersion, "tasks", List.of("detect"), "roi", bad));
                assertThat(refused.statusCode()).as(bad + " " + new String(refused.body())).isEqualTo(422);
                assertThat(new String(refused.body())).contains("ROI_MALFORMED");
            }
            assertThat(post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "bad-notobject", "artifactId", ghost,
                    "artifactVersionId", ghostVersion, "tasks", List.of("detect"), "roi", "0,0,10,10")).statusCode())
                    .isEqualTo(422);
            assertThat(RIGHTS.calls.get()).as("rights authority never consulted for structural faults").isEqualTo(rightsCalls);

            // Out-of-frame (video and image): typed refusal, no model call.
            for (var target : List.of(clip, image)) {
                for (Map<String, Object> outside : List.of(roi(600, 0, 100, 50), roi(0, 340, 50, 50),
                        roi(640, 0, 1, 1), roi(0, 0, 641, 360), roi(0, 0, 640, 361))) {
                    HttpResponse<byte[]> refused = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "oof-"
                            + target.artifactId().substring(0, 8) + outside.hashCode(), "artifactId", target.artifactId(),
                            "artifactVersionId", target.version().value(), "tasks", List.of("detect"), "roi", outside));
                    assertThat(refused.statusCode()).as(outside + " " + new String(refused.body())).isEqualTo(422);
                    assertThat(new String(refused.body())).contains("ROI_OUT_OF_FRAME");
                }
            }
            // A video frame index beyond the timeline is also a typed refusal.
            HttpResponse<byte[]> badFrame = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "bad-frame",
                    "artifactId", clip.artifactId(), "artifactVersionId", clip.version().value(),
                    "tasks", List.of("detect"), "frameIndex", 9999, "roi", roi(0, 0, 10, 10)));
            assertThat(badFrame.statusCode()).isEqualTo(422);
            assertThat(new String(badFrame.body())).contains("FRAME_INDEX_OUT_OF_RANGE");
            assertThat(proxy.analyzeCalls.get()).as("no model call for any refused ROI").isEqualTo(calls);
            // An ROI exactly equal to the frame is valid (boundary).
            HttpResponse<byte[]> full = post(server, ROI, PRINCIPAL, ALL, Map.of("requestId", "full-frame",
                    "artifactId", image.artifactId(), "artifactVersionId", image.version().value(),
                    "tasks", List.of("ocr"), "roi", roi(0, 0, 640, 360)));
            assertThat(full.statusCode()).as(new String(full.body())).isEqualTo(201);
            assertThat(proxy.analyzeCalls.get()).isEqualTo(calls + 1);
        } finally {
            server.stop(0);
        }
    }

