    private void verifyTracks(boolean vfr, String requestId) throws Exception {
        Path root = Files.createTempDirectory("media-dev-vision-tr-");
        MediaRuntime runtime = runtime(root);
        HttpServer server = server(runtime, RIGHTS.verdict(Verdict.ADMITTED));
        try {
            byte[] video = TrackingVideoFixture.generate(ffmpeg, Files.createTempDirectory(work, "gen-"), vfr);
            Path videoFile = work.resolve(vfr ? "probe-vfr.mp4" : "probe-cfr.mp4");
            Files.write(videoFile, video);
            TrackingVideoFixture.Probe probe = TrackingVideoFixture.probe(ffprobe, videoFile);
            MediaArtifact source = upload(runtime, vfr ? "vfr.mp4" : "cfr.mp4", "video/mp4", video);

            int before = proxy.analyzeCalls.get();
            HttpResponse<byte[]> created = post(server, TRACKS, PRINCIPAL, ALL, Map.of("requestId", requestId,
                    "artifactId", source.artifactId(), "artifactVersionId", source.version().value(),
                    "maxFrames", 16));
            assertThat(created.statusCode()).as(new String(created.body())).isEqualTo(201);
            Map<String, Object> view = map(created);
            assertThat(view).containsEntry("scope", "DEV_ONLY").containsEntry("replayed", false);
            Map<String, Object> document = readDocument(runtime, (String) view.get("outputId"));
            System.out.println("J05-TRACKS-" + (vfr ? "VFR" : "CFR") + " " + JSON.writeValueAsString(document));

            // Lineage binds the exact source version digest and the digest-qualified model.
            Map<String, Object> lineage = obj(view.get("lineage"));
            assertThat(obj(lineage.get("source"))).containsEntry("artifactVersionId", source.version().value())
                    .containsEntry("sha256", source.sha256()).containsEntry("contentType", "video/mp4");
            assertThat(obj(((List<?>) lineage.get("models")).get(0))).containsEntry("id", LocalVisionEngine.FLORENCE_MODEL_ID)
                    .containsEntry("spdxLicense", "MIT");
            assertThat(obj(lineage.get("tracking"))).containsEntry("algorithm", "GREEDY_IOU_LABEL_V1");

            // The probed timeline is real: rational time base, PTS order, VFR flag.
            Map<String, Object> videoView = obj(document.get("video"));
            assertThat(obj(videoView.get("timeBase"))).containsEntry("num", (int) probe.timeBaseNum())
                    .containsEntry("den", (int) probe.timeBaseDen());
            assertThat(videoView).containsEntry("width", TrackingVideoFixture.WIDTH)
                    .containsEntry("height", TrackingVideoFixture.HEIGHT)
                    .containsEntry("frameCount", probe.pts().size());
            assertThat(videoView.get("variableFrameRate")).isEqualTo(vfr);
            if (vfr) {
                assertThat(probe.pts().size()).as("frames were dropped").isLessThan(30);
                assertThat(new java.util.HashSet<>(deltas(probe.pts()))).hasSizeGreaterThan(1);
            }

            // Every sampled frame's PTS equals ffprobe's PTS for the same PTS-order ordinal.
            List<Map<String, Object>> frames = list(document.get("frames"));
            assertThat(frames).hasSizeGreaterThanOrEqualTo(10);
            assertThat(proxy.analyzeCalls.get() - before).isEqualTo(frames.size());
            for (Map<String, Object> frame : frames) {
                int index = ((Number) frame.get("frameIndex")).intValue();
                assertThat(((Number) frame.get("pts")).longValue()).isEqualTo(probe.pts().get(index));
                assertThat(((Number) frame.get("rejectedDetections")).intValue()).isZero();
            }

            // Tracks follow the analytic motion: one car track and one person track covering the sampled frames.
            List<Map<String, Object>> tracks = list(document.get("tracks"));
            Map<String, Object> car = longest(tracks, "car");
            Map<String, Object> person = longest(tracks, "person");
            assertThat(car).as("car track").isNotNull();
            assertThat(person).as("person track").isNotNull();
            Stats carStats = score(car, probe, true);
            Stats personStats = score(person, probe, false);
            System.out.println("J05-ACCURACY " + (vfr ? "VFR" : "CFR") + " sampledFrames=" + frames.size()
                    + " car{obs=" + carStats.count + " meanIoU=" + carStats.meanIou() + " minIoU=" + carStats.minIou
                    + " maxCenterErrPx=" + carStats.maxCenter + "} person{obs=" + personStats.count + " meanIoU="
                    + personStats.meanIou() + " minIoU=" + personStats.minIou + " maxCenterErrPx="
                    + personStats.maxCenter + "} tracks=" + tracks.size());
            assertThat(carStats.count).isGreaterThanOrEqualTo(frames.size() - 1);
            assertThat(personStats.count).isGreaterThanOrEqualTo(frames.size() - 1);
            assertThat(carStats.minIou).isGreaterThanOrEqualTo(0.75);
            assertThat(personStats.minIou).isGreaterThanOrEqualTo(0.75);
            assertThat(carStats.maxCenter).isLessThanOrEqualTo(8.0);
            assertThat(personStats.maxCenter).isLessThanOrEqualTo(8.0);
            // No identity switch: exactly one track per labelled object that has more than a stray observation.
            assertThat(tracks.stream().filter(t -> "car".equals(t.get("label"))
                    && ((Number) t.get("observationCount")).intValue() > 2)).hasSize(1);
            assertThat(tracks.stream().filter(t -> "person".equals(t.get("label"))
                    && ((Number) t.get("observationCount")).intValue() > 2)).hasSize(1);
            // The whole truth is moving: the first and last car boxes differ by the known displacement.
            List<Map<String, Object>> carObs = list(car.get("observations"));
            double firstX = number(obj(carObs.get(0).get("box")).get("x"));
            double lastX = number(obj(carObs.get(carObs.size() - 1).get("box")).get("x"));
            long spanTicks = ((Number) carObs.get(carObs.size() - 1).get("pts")).longValue()
                    - ((Number) carObs.get(0).get("pts")).longValue();
            double expectedDx = 90.0 * spanTicks * probe.timeBaseNum() / probe.timeBaseDen();
            assertThat(lastX - firstX).isBetween(expectedDx - 6, expectedDx + 6);

            // Idempotent replay: same requestId re-derives identical bytes, same artifact, 200 replayed.
            HttpResponse<byte[]> replay = post(server, TRACKS, PRINCIPAL, ALL, Map.of("requestId", requestId,
                    "artifactId", source.artifactId(), "artifactVersionId", source.version().value(), "maxFrames", 16));
            assertThat(replay.statusCode()).as(new String(replay.body())).isEqualTo(200);
            assertThat(map(replay)).containsEntry("replayed", true).containsEntry("outputId", view.get("outputId"));
            // The same requestId for a different request is refused.
            assertThat(post(server, TRACKS, PRINCIPAL, ALL, Map.of("requestId", requestId,
                    "artifactId", source.artifactId(), "artifactVersionId", source.version().value(), "maxFrames", 8))
                    .statusCode()).isEqualTo(409);
        } finally {
            server.stop(0);
        }
    }

