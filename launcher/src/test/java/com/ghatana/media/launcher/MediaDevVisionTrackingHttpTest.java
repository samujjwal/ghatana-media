    private record Stats(int count, double sumIou, double minIou, double maxCenter) {
        double meanIou() { return Math.round(sumIou / Math.max(1, count) * 1000.0) / 1000.0; }
    }

    private static Stats score(Map<String, Object> track, TrackingVideoFixture.Probe probe, boolean car) {
        int count = 0;
        double sum = 0;
        double min = 1;
        double maxCenter = 0;
        for (Map<String, Object> observation : list(track.get("observations"))) {
            double seconds = ((Number) observation.get("pts")).longValue() * (double) probe.timeBaseNum()
                    / probe.timeBaseDen();
            double[] truth = car ? TrackingVideoFixture.carBox(seconds) : TrackingVideoFixture.personBox(seconds);
            double[] actual = box(obj(observation.get("box")));
            double iou = TrackingVideoFixture.iou(truth, actual);
            sum += iou;
            min = Math.min(min, iou);
            maxCenter = Math.max(maxCenter, TrackingVideoFixture.centerError(truth, actual));
            count++;
            // Boxes are inside the frame in source pixels.
            assertThat(actual[0]).isGreaterThanOrEqualTo(0);
            assertThat(actual[1]).isGreaterThanOrEqualTo(0);
            assertThat(actual[0] + actual[2]).isLessThanOrEqualTo(TrackingVideoFixture.WIDTH);
            assertThat(actual[1] + actual[3]).isLessThanOrEqualTo(TrackingVideoFixture.HEIGHT);
        }
        return new Stats(count, sum, min, Math.round(maxCenter * 100.0) / 100.0);
    }

    private static Map<String, Object> longest(List<Map<String, Object>> tracks, String label) {
        return tracks.stream().filter(t -> label.equals(t.get("label")))
                .max(java.util.Comparator.comparingInt(t -> ((Number) t.get("observationCount")).intValue()))
                .orElse(null);
    }

    private static List<Long> deltas(List<Long> pts) {
        List<Long> out = new ArrayList<>();
        for (int i = 1; i < pts.size(); i++) out.add(pts.get(i) - pts.get(i - 1));
        return out;
    }

    private static double[] box(Map<String, Object> box) {
        return new double[] {number(box.get("x")), number(box.get("y")), number(box.get("width")), number(box.get("height"))};
    }

    private static double number(Object value) { return ((Number) value).doubleValue(); }

