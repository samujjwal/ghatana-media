    /** Loopback reverse proxy to the real sidecar that counts analyze calls and can kill the sidecar mid-run. */
    private static final class SidecarProxy implements AutoCloseable {
        final HttpServer server;
        final AtomicInteger analyzeCalls = new AtomicInteger();
        private volatile LocalVisionSidecarProcess target;
        private volatile int killAt = -1;
        private volatile Runnable killHook = () -> { };
        private volatile boolean dropping;
        private final HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).build();

        SidecarProxy(LocalVisionSidecarProcess target) throws Exception {
            this.target = target;
            server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
            server.createContext("/", exchange -> {
                try {
                    if (dropping) { exchange.close(); return; }
                    byte[] request = exchange.getRequestBody().readAllBytes();
                    // The CURRENT target (not the constructor argument): a replacement sidecar changes it.
                    LocalVisionSidecarProcess current = SidecarProxy.this.target;
                    HttpRequest.Builder builder = HttpRequest.newBuilder(
                                    current.baseUri().resolve(exchange.getRequestURI().getPath()))
                            .timeout(Duration.ofMinutes(8))
                            .header("Authorization", "Bearer " + current.token());
                    if (exchange.getRequestHeaders().getFirst("Content-Type") != null) {
                        builder.header("Content-Type", exchange.getRequestHeaders().getFirst("Content-Type"));
                    }
                    HttpResponse<byte[]> response = http.send("GET".equals(exchange.getRequestMethod())
                            ? builder.GET().build() : builder.POST(HttpRequest.BodyPublishers.ofByteArray(request)).build(),
                            HttpResponse.BodyHandlers.ofByteArray());
                    exchange.getResponseHeaders().set("Content-Type", "application/json");
                    exchange.sendResponseHeaders(response.statusCode(), response.body().length);
                    exchange.getResponseBody().write(response.body());
                    exchange.close();
                    if ("/v1/analyze".equals(exchange.getRequestURI().getPath())) {
                        int n = analyzeCalls.incrementAndGet();
                        if (n == killAt) {
                            killAt = -1;
                            killHook.run();
                            dropping = true;
                        }
                    }
                } catch (Exception failure) {
                    System.out.println("J05-PROXY-FAILURE " + failure);
                    exchange.close();
                }
            });
            server.start();
        }

        URI uri() { return URI.create("http://127.0.0.1:" + server.getAddress().getPort()); }

        void killAfter(int nthAnalyze, Runnable hook) { this.killAt = nthAnalyze; this.killHook = hook; }

        void retarget(LocalVisionSidecarProcess replacement) { this.target = replacement; this.dropping = false; }

        @Override public void close() { server.stop(0); }
    }

    /** Fixture resolver with a switchable verdict and a call counter (FIXTURE_ONLY: not a rights grant). */
    private static final class CountingResolver {
        final AtomicInteger calls = new AtomicInteger();

        RightsConsentResolver verdict(Verdict verdict) {
            return new RightsConsentResolver() {
                @Override public String resolverId() { return "fixture-only-rights-resolver"; }
                @Override public boolean ready() { return true; }
                @Override public Resolution resolve(com.ghatana.media.runtime.MediaRightsConsentContracts.ResolutionRequest r) {
                    calls.incrementAndGet();
                    assertThat(r.scope()).isEqualTo(Scope.PROCESSING);
                    return verdict == Verdict.ADMITTED
                            ? new Resolution(verdict, Set.of(), List.of("fixture-attestation-1"), resolverId())
                            : new Resolution(verdict, Set.of(Reason.NO_ATTESTATION), List.of(), resolverId());
                }
            };
        }
    }

