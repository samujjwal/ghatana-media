    @Test
    void rendersVideoAudioCaptionsGraphicAndColourAndMeasuresTheDecodedMaster() throws Exception {
        tools();
        Path root = Files.createTempDirectory("media-dev-composite-http-");
        Path temp = Files.createDirectories(root.resolve("work"));
        MediaRuntime runtime = runtime(root.resolve("store"), 4, 4);
        HttpServer server = server(runtime, config(temp, "ultrafast", 120, 64L << 20, 0));
        try {
            String base = base(server);
            Fixture fx = fixture(base, runtime, root);
            Map<String, Object> spec = spec(fx.revisionId, "r-main", "BOTH", null);
            HttpResponse<String> created = post(base, spec);
            assertThat(created.statusCode()).as(created.body()).isEqualTo(201);
            String renderTimerCount = runtime.prometheusMetrics().lines()
                    .filter(line -> line.startsWith("media_workflow_stage_duration_seconds_count{"))
                    .filter(line -> line.contains("stage=\"render\""))
                    .findFirst().orElseThrow(() -> new AssertionError("composite render duration was not scraped"));
            assertThat(renderTimerCount).contains("contract_version=\"v1\"", "service=\"launcher\"", "stage=\"render\"")
                    .doesNotContain("tenant", "principal", "project", "artifact", "request", "revision", "source", "digest")
                    .endsWith(" 1");
            String labelSet = renderTimerCount.substring(renderTimerCount.indexOf('{') + 1, renderTimerCount.indexOf('}'));
            assertThat(labelSet.split(",")).hasSize(3);
            Map<String, Object> body = read(created.body());
            Map<String, Object> artifact = object(body.get("artifact"));
            assertThat(artifact).containsEntry("contentType", "video/mp4");
            Path mp4 = root.resolve("master.mp4");
            Files.write(mp4, content(runtime, (String) body.get("renderId")));
            assertThat(HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256")
                    .digest(Files.readAllBytes(mp4)))).as("checksum of registered bytes").isEqualTo(artifact.get("sha256"));

            // ---- container, codecs, exact frame count and duration (independent ffprobe) ----
            var probe = JSON.readTree(run(ffprobe, "-v", "error", "-count_frames", "-show_entries",
                    "stream=codec_type,codec_name,width,height,r_frame_rate,nb_read_frames,pix_fmt,duration,channels,sample_rate"
                            + ":format=duration", "-of", "json", mp4.toString()));
            int video = 0, audio = 0, subtitle = 0;
            for (var stream : probe.path("streams")) {
                switch (stream.path("codec_type").asString()) {
                    case "video" -> {
                        video++;
                        assertThat(stream.path("codec_name").asString()).isEqualTo("h264");
                        assertThat(stream.path("pix_fmt").asString()).isEqualTo("yuv420p");
                        assertThat(stream.path("width").asInt()).isEqualTo(W);
                        assertThat(stream.path("height").asInt()).isEqualTo(H);
                        assertThat(stream.path("r_frame_rate").asString()).isEqualTo("25/1");
                        assertThat(stream.path("nb_read_frames").asString()).isEqualTo("100");
                    }
                    case "audio" -> {
                        audio++;
                        assertThat(stream.path("codec_name").asString()).isEqualTo("aac");
                        assertThat(stream.path("channels").asInt()).isEqualTo(2);
                        assertThat(Double.parseDouble(stream.path("duration").asString())).isBetween(3.95, 4.05);
                    }
                    case "subtitle" -> {
                        subtitle++;
                        assertThat(stream.path("codec_name").asString()).isEqualTo("mov_text");
                    }
                    default -> { }
                }
            }
            assertThat(new int[] {video, audio, subtitle}).containsExactly(1, 1, 1);
            assertThat(Double.parseDouble(probe.path("format").path("duration").asString())).isBetween(3.99, 4.05);

            // ---- each clip's content at its timeline position (frame signatures); conformed 30 fps / 640x360 source ----
            assertThat(nearly(frame(mp4, 5), 160, 60, 0, 255, 0)).as("A green @ frame 5").isTrue();
            assertThat(nearly(frame(mp4, 24), 160, 60, 0, 255, 0)).as("last green frame").isTrue();
            assertThat(nearly(frame(mp4, 25), 160, 60, 0, 0, 255)).as("first blue frame").isTrue();
            assertThat(nearly(frame(mp4, 49), 160, 60, 0, 0, 255)).as("last blue frame").isTrue();
            assertThat(nearly(frame(mp4, 50), 250, 60, 255, 255, 255)).as("B white from frame 50").isTrue();
            assertThat(nearly(frame(mp4, 74), 250, 60, 255, 255, 255)).isTrue();
            assertThat(nearly(frame(mp4, 75), 250, 60, 0, 0, 0)).as("B black from frame 75").isTrue();
            assertThat(nearly(frame(mp4, 99), 250, 60, 0, 0, 0)).isTrue();
            // 640x360 conformed into 320x240 with letterbox bars: the bar rows are black while the image is white.
            assertThat(nearly(frame(mp4, 60), 250, 5, 0, 0, 0)).as("top letterbox bar").isTrue();
            assertThat(nearly(frame(mp4, 60), 250, 120, 255, 255, 255)).as("image area").isTrue();

            // ---- overlay graphic: pixels at the expected position and only inside its window ----
            assertThat(nearly(frame(mp4, 49), 30, 110, 0, 0, 255)).as("before the overlay window").isTrue();
            assertThat(nearly(frame(mp4, 50), 30, 110, 255, 0, 255)).as("overlay first frame (magenta)").isTrue();
            assertThat(nearly(frame(mp4, 60), 30, 110, 255, 0, 255)).isTrue();
            assertThat(nearly(frame(mp4, 60), 30, 144, 255, 255, 255)).as("below the 100x30 graphic").isTrue();
            assertThat(nearly(frame(mp4, 60), 125, 110, 255, 255, 255)).as("right of the graphic").isTrue();
            assertThat(nearly(frame(mp4, 99), 30, 110, 255, 0, 255)).isTrue();

            // ---- audio / video sync: the 1 kHz beep onset (story 1.000 s) vs the green to blue cut (frame 25) ----
            short[] pcm = audio(mp4);
            double onset = beepOnsetSeconds(pcm);
            int cutFrame = 25;
            assertThat(Math.abs(onset - cutFrame / (double) FPS)).as("beep onset " + onset + " vs cut").isLessThanOrEqualTo(1.0 / FPS);
            // Music at -12 dB under the beep: 220 Hz amplitude 0.5 * 10^(-12/20) of full scale.
            double music = toneAmplitude(pcm, 2.2, 3.5, 220);
            assertThat(music).isBetween(0.5 * 0.2512 * 32767 * 0.85, 0.5 * 0.2512 * 32767 * 1.15);

            // ---- captions: muxed cue timing exact, burned cue visible exactly inside its window ----
            List<String> cues = subtitleCues(mp4);
            assertThat(cues).containsExactly("00:00:00,500 --> 00:00:01,500 Hello world", "00:00:02,500 --> 00:00:03,500 Second cue");
            Path plain = root.resolve("plain.mp4");
            HttpResponse<String> unburned = post(base, spec(fx.revisionId, "r-mux", "MUX", null));
            assertThat(unburned.statusCode()).as(unburned.body()).isEqualTo(201);
            Files.write(plain, content(runtime, (String) read(unburned.body()).get("renderId")));
            assertThat(burnedPixels(mp4, plain, 12)).as("before cue 1").isZero();
            assertThat(burnedPixels(mp4, plain, 13)).as("first cue frame").isGreaterThan(150);
            assertThat(burnedPixels(mp4, plain, 37)).as("last cue frame").isGreaterThan(150);
            assertThat(burnedPixels(mp4, plain, 38)).as("after cue 1").isZero();
            assertThat(burnedPixels(mp4, plain, 62)).as("before cue 2").isZero();
            assertThat(burnedPixels(mp4, plain, 63)).as("cue 2").isGreaterThan(150);

            // ---- lineage names every exact source version (erasure follows sources[]); rights recorded ----
            Map<String, Object> lineage = object(body.get("lineage"));
            List<?> sources = (List<?>) lineage.get("sources");
            assertThat(sources).hasSize(6);
            List<String> sourceIds = sources.stream().map(s -> (String) object(s).get("artifactId")).toList();
            assertThat(sourceIds).containsExactlyInAnyOrder(fx.a.artifactId(), fx.b.artifactId(), fx.narration.artifactId(),
                    fx.music.artifactId(), fx.graphic.artifactId(), fx.vtt.artifactId());
            for (Object source : sources) {
                Map<String, Object> entry = object(source);
                assertThat(entry.get("artifactVersionId")).asString().startsWith("sha256:");
                assertThat(entry.get("sha256")).asString().hasSize(64);
            }
            assertThat(String.valueOf(lineage.get("rightsDecision"))).contains("att-" + fx.a.artifactId());
            assertThat(object(lineage.get("encoding"))).containsEntry("videoFrameCount", 100).containsEntry("embeddedClipAudioUsed", false);
            assertThat(object(lineage.get("parent")).get("artifactId")).isEqualTo(sourceIds.get(0));

            // ---- idempotency: replay is 200 with the same artifact; the same requestId with other params is 409 ----
            int before = registrations.get();
            HttpResponse<String> replay = post(base, spec);
            assertThat(replay.statusCode()).as(replay.body()).isEqualTo(200);
            assertThat(read(replay.body())).containsEntry("renderId", body.get("renderId")).containsEntry("replayed", true);
            assertThat(registrations.get()).isEqualTo(before);
            Map<String, Object> changed = spec(fx.revisionId, "r-main", "BOTH", Map.of("brightness", 0.1));
            HttpResponse<String> reuse = post(base, changed);
            assertThat(reuse.statusCode()).as(reuse.body()).isEqualTo(409);
            assertThat(reuse.body()).contains("REQUEST_ID_REUSED");

            // ---- reproducibility: a different requestId renders identical decoded frames and audio ----
            Path again = root.resolve("again.mp4");
            HttpResponse<String> second = post(base, spec(fx.revisionId, "r-again", "BOTH", null));
            assertThat(second.statusCode()).as(second.body()).isEqualTo(201);
            Files.write(again, content(runtime, (String) read(second.body()).get("renderId")));
            assertThat(decodedMd5(mp4)).as("decoded A/V of two renders of the same inputs").isEqualTo(decodedMd5(again));

            // ---- readback in owner scope only ----
            String renderId = (String) body.get("renderId");
            assertThat(send(base, "GET", "/dev/v1/composite-renders/" + renderId, null, OWNER, RENDER_PERMISSIONS).statusCode())
                    .isEqualTo(200);
            assertThat(send(base, "GET", "/dev/v1/composite-renders/" + renderId, null, OTHER, RENDER_PERMISSIONS).statusCode())
                    .isEqualTo(404);

            // ---- colour adjustment measured against the un-graded render ----
            double[] base0 = lumaSat(mp4, 60, 250, 100);
            Path dim1 = root.resolve("dim1.mp4"), dim2 = root.resolve("dim2.mp4"), desat = root.resolve("desat.mp4");
            Files.write(dim1, content(runtime, renderOf(base, fx, "c-1", Map.of("brightness", -0.1))));
            Files.write(dim2, content(runtime, renderOf(base, fx, "c-2", Map.of("brightness", -0.2))));
            Files.write(desat, content(runtime, renderOf(base, fx, "c-3", Map.of("saturation", 0.5))));
            double d1 = base0[0] - lumaSat(dim1, 60, 250, 100)[0];
            double d2 = base0[0] - lumaSat(dim2, 60, 250, 100)[0];
            assertThat(d1).as("luma drop for brightness -0.1").isBetween(15.0, 35.0);
            assertThat(d2 / d1).as("brightness is proportional").isBetween(1.8, 2.2);
            double blue0 = chroma(mp4, 30, 250, 100), blue1 = chroma(desat, 30, 250, 100);
            assertThat(blue1 / blue0).as("saturation 0.5 halves the chroma magnitude of the blue clip").isBetween(0.44, 0.56);
            Path grey = root.resolve("grey.mp4");
            Files.write(grey, content(runtime, renderOf(base, fx, "c-4", Map.of("saturation", 0.0))));
            assertThat(chroma(grey, 30, 250, 100)).as("saturation 0 is grey").isLessThan(3.0);
        } finally {
            server.stop(0);
            deleteTree(root);
        }
    }

