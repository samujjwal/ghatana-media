    private BufferedImage frame(Path mp4, int index) throws Exception {
        byte[] png = runBytes(ffmpeg, "-hide_banner", "-loglevel", "error", "-i", mp4.toString(), "-vf",
                "select=eq(n\\," + index + ")", "-frames:v", "1", "-f", "image2pipe", "-vcodec", "png", "-");
        return ImageIO.read(new ByteArrayInputStream(png));
    }

    private static boolean nearly(BufferedImage image, int x, int y, int r, int g, int b) {
        int rgb = image.getRGB(x, y);
        return Math.abs(((rgb >> 16) & 0xff) - r) <= 24 && Math.abs(((rgb >> 8) & 0xff) - g) <= 24
                && Math.abs((rgb & 0xff) - b) <= 24;
    }

    private short[] audio(Path mp4) throws Exception {
        byte[] raw = runBytes(ffmpeg, "-hide_banner", "-loglevel", "error", "-i", mp4.toString(), "-vn", "-af", "pan=mono|c0=c0",
                "-f", "s16le", "-ar", "48000", "-");
        short[] pcm = new short[raw.length / 2];
        java.nio.ByteBuffer.wrap(raw).order(java.nio.ByteOrder.LITTLE_ENDIAN).asShortBuffer().get(pcm);
        return pcm;
    }

    /** First instant where the 1 kHz marker (amplitude 0.5, far above the -12 dB music) is present. */
    private static double beepOnsetSeconds(short[] pcm) {
        for (int i = 0; i < pcm.length; i++) {
            if (Math.abs(pcm[i]) > 0.3 * 32767 * 0.9) return i / 48_000.0;
        }
        return -1;
    }

    private static double toneAmplitude(short[] pcm, double from, double to, double hz) {
        int start = (int) (from * 48_000), end = (int) (to * 48_000);
        double re = 0, im = 0;
        for (int i = start; i < end; i++) {
            double phase = 2 * Math.PI * hz * i / 48_000.0;
            re += pcm[i] * Math.cos(phase);
            im += pcm[i] * Math.sin(phase);
        }
        return 2 * Math.hypot(re, im) / (end - start);
    }

    private List<String> subtitleCues(Path mp4) throws Exception {
        String srt = new String(runBytes(ffmpeg, "-hide_banner", "-loglevel", "error", "-i", mp4.toString(), "-map", "0:s:0",
                "-f", "srt", "-"), StandardCharsets.UTF_8);
        List<String> cues = new ArrayList<>();
        for (String block : srt.trim().split("\\n\\n")) {
            String[] lines = block.trim().split("\\n");
            cues.add(lines[1] + " " + String.join(" ", java.util.Arrays.copyOfRange(lines, 2, lines.length)));
        }
        return cues;
    }

    /** Pixels in the lower caption band that differ strongly between the burned and the un-burned render. */
    private int burnedPixels(Path burned, Path plain, int index) throws Exception {
        BufferedImage x = frame(burned, index), y = frame(plain, index);
        int count = 0;
        for (int py = 170; py < H; py++) {
            for (int px = 0; px < W; px++) {
                int p = x.getRGB(px, py), q = y.getRGB(px, py);
                int delta = Math.abs(((p >> 16) & 0xff) - ((q >> 16) & 0xff)) + Math.abs(((p >> 8) & 0xff) - ((q >> 8) & 0xff))
                        + Math.abs((p & 0xff) - (q & 0xff));
                if (delta > 120) count++;
            }
        }
        return count;
    }

    private String decodedMd5(Path mp4) throws Exception {
        return run(ffmpeg, "-hide_banner", "-loglevel", "error", "-i", mp4.toString(), "-map", "0:v:0", "-map", "0:a:0",
                "-f", "md5", "-").trim();
    }

    /** {luma 0..255, HSV saturation 0..1} of one pixel of one decoded frame. */
    private double[] lumaSat(Path mp4, int index, int x, int y) throws Exception {
        int rgb = frame(mp4, index).getRGB(x, y);
        double r = (rgb >> 16) & 0xff, g = (rgb >> 8) & 0xff, b = rgb & 0xff;
        double max = Math.max(r, Math.max(g, b)), min = Math.min(r, Math.min(g, b));
        return new double[] {0.299 * r + 0.587 * g + 0.114 * b, max == 0 ? 0 : (max - min) / max};
    }

    /** Chroma magnitude sqrt((U-128)^2 + (V-128)^2) of one decoded pixel in YUV 4:4:4 (no RGB clipping involved). */
    private double chroma(Path mp4, int index, int x, int y) throws Exception {
        byte[] raw = runBytes(ffmpeg, "-hide_banner", "-loglevel", "error", "-i", mp4.toString(), "-vf",
                "select=eq(n\\," + index + ")", "-frames:v", "1", "-pix_fmt", "yuv444p", "-f", "rawvideo", "-");
        int u = raw[W * H + y * W + x] & 0xff, v = raw[2 * W * H + y * W + x] & 0xff;
        return Math.hypot(u - 128, v - 128);
    }

