    private Path awaitWorkDirWithEncoder(Path temp) throws Exception {
        long deadline = System.nanoTime() + Duration.ofSeconds(60).toNanos();
        while (System.nanoTime() < deadline) {
            try (var dirs = Files.list(temp)) {
                for (Path dir : dirs.toList()) {
                    if (encoderAlive(dir)) return dir;
                }
            }
            Thread.sleep(50);
        }
        throw new AssertionError("no running encoder was observed");
    }

    private static boolean encoderAlive(Path workDir) {
        return ProcessHandle.allProcesses().anyMatch(handle -> handle.isAlive() && handle.info().commandLine()
                .map(line -> line.contains(workDir.toString()) && line.contains("libx264")).orElse(false));
    }

    private static String run(String... command) throws Exception {
        return new String(runBytes(command), StandardCharsets.UTF_8);
    }

    private static byte[] runBytes(String... command) throws Exception {
        Process process = new ProcessBuilder(command).redirectError(ProcessBuilder.Redirect.DISCARD).start();
        byte[] out = process.getInputStream().readAllBytes();
        if (process.waitFor() != 0) throw new AssertionError("command failed: " + String.join(" ", command));
        return out;
    }

    private static MediaArtifact upload(MediaRuntime runtime, String name, String contentType, byte[] bytes) throws Exception {
        String digest = HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(bytes));
        var session = runtime.beginUpload(new UploadRequest(TENANT, OWNER, name, contentType, bytes.length, digest,
                "INTERNAL", Duration.ofMinutes(30), Map.of()), "fixture-" + name + "-" + digest);
        int chunk = runtime.config().maximumChunkBytes();
        for (int offset = 0, index = 0; offset < bytes.length; offset += chunk, index++) {
            runtime.appendChunk(TENANT, OWNER, session.uploadId(), index,
                    java.util.Arrays.copyOfRange(bytes, offset, Math.min(bytes.length, offset + chunk)));
        }
        return runtime.completeUpload(TENANT, OWNER, session.uploadId());
    }

